import { test, expect } from '@playwright/test'

test('login, search, streamed answer, citation, upload and evaluation', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('邮箱地址').fill('admin@acme.demo')
  await page.getByLabel('登录密码').fill(process.env.KNOWFLOW_DEMO_PASSWORD || 'KnowFlowDemo!2026')
  await page.getByRole('button', { name: '登录工作空间' }).click()
  await expect(page.getByRole('heading', { name: '知识，从这里连接' })).toBeVisible()
  await page.screenshot({ path: '../docs/demo/workspace.png', fullPage: true })
  await page.getByRole('link', { name: '检索调试' }).click()
  await page.locator('.retrieval-form select').selectOption({ label: '企业知识中心' })
  await page.getByLabel('检索问题').fill('退款审核需要几天？')
  await page.getByRole('button', { name: '检索', exact: true }).click()
  await expect(page.locator('.result-card').first()).toContainText('退款政策')
  await page.getByRole('link', { name: '知识问答' }).click()
  await page.getByLabel('输入问题').fill('退款超过30天还能申请吗？')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.message.assistant')).toContainText('30 天')
  await expect(page.getByRole('button', { name: '发送', exact: true })).toBeVisible()
  await page.locator('.message.assistant .references button').filter({ hasText: '退款政策' }).first().click()
  await expect(page.locator('.source-drawer')).toContainText('退款政策')
  await expect(page.locator('.source-excerpt')).toContainText('30 天')
  await page.screenshot({ path: '../docs/demo/answer-reference.png', fullPage: true })
  await page.getByRole('button', { name: '关闭引用' }).click()
  await page.getByRole('link', { name: '知识空间' }).click()
  const title = `浏览器验收-${Date.now()}.md`
  await page.locator('input[type=file]').setInputFiles({ name: title, mimeType: 'text/markdown', buffer: Buffer.from('# 验收资料\n\n设备报修请联系技术支持团队。', 'utf8') })
  await expect(page.locator('tr', { hasText: title })).toContainText('已就绪')
  page.on('dialog', dialog => dialog.accept())
  await page.locator('tr', { hasText: title }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('tr', { hasText: title })).toHaveCount(0)
  await page.getByRole('link', { name: '效果评估' }).click()
  await page.getByLabel('评估数据集').selectOption({ label: '演示召回开发集 · v1' })
  const [evaluation] = await Promise.all([page.waitForResponse(r => r.url().endsWith('/evaluations/runs') && r.request().method() === 'POST'), page.getByRole('button', { name: '运行评估' }).click()])
  const evaluationId = (await evaluation.json()).id
  await expect(page.locator('.eval-row').filter({ hasText: evaluationId.slice(0, 8) }).getByText('COMPLETED', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '调用记录' }).click()
  await expect(page.getByRole('heading', { name: '回答生成服务' })).toBeVisible()
  await page.getByRole('button', { name: '检查生成服务' }).click()
  await expect(page.locator('.probe-result')).toContainText('检查通过')
  await page.getByRole('button', { name: '检查向量服务' }).click()
  await expect(page.locator('.probe-result')).toHaveCount(2)
  const originalTenant = await page.getByLabel('租户每日额度').inputValue()
  const originalUser = await page.getByLabel('每人每日额度').inputValue()
  await page.getByLabel('租户每日额度').fill('800000')
  await page.getByLabel('每人每日额度').fill('90000')
  await Promise.all([page.waitForResponse(r => r.url().endsWith('/monitoring/quota') && r.request().method() === 'PUT'), page.getByRole('button', { name: '保存额度' }).click()])
  await expect(page.locator('.quota-panel')).toContainText('90,000')
  await page.getByLabel('租户每日额度').fill(originalTenant)
  await page.getByLabel('每人每日额度').fill(originalUser)
  await Promise.all([page.waitForResponse(r => r.url().endsWith('/monitoring/quota') && r.request().method() === 'PUT'), page.getByRole('button', { name: '保存额度' }).click()])
  await page.screenshot({ path: '../docs/demo/models-and-quota.png', fullPage: true })
  expect(errors).toEqual([])
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: '知识问答' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../docs/demo/mobile.png', fullPage: true })
})
