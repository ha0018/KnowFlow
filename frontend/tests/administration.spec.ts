import { test, expect } from '@playwright/test'

test('member, role and document access changes take effect in another session', async ({ page, browser }) => {
  test.setTimeout(180000)
  const suffix = Date.now().toString(), email = `browser-${suffix}@acme.demo`, password = 'BrowserMember!2026'
  const roleName = `资料验收角色 ${suffix}`, name = `授权验收 ${suffix}`
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('邮箱地址').fill('admin@acme.demo')
  await page.getByLabel('登录密码').fill(process.env.KNOWFLOW_DEMO_PASSWORD || 'KnowFlowDemo!2026')
  await page.getByRole('button', { name: '登录工作空间' }).click()
  await page.getByRole('link', { name: '成员与角色' }).click()
  await page.getByLabel('角色代码').fill(`browser-${suffix}`)
  await page.getByLabel('角色名称').fill(roleName)
  await page.getByRole('checkbox', { name: '执行 Agent' }).check()
  await page.getByRole('button', { name: '保存角色', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('角色已保存')
  await page.getByLabel('成员姓名').fill(name)
  await page.getByLabel('成员邮箱').fill(email)
  await page.getByLabel('初始密码').fill(password)
  await page.getByRole('button', { name: '创建成员', exact: true }).click()
  const member = page.locator('tr', { hasText: email })
  await member.getByRole('button', { name: `分配角色 ${email}`, exact: true }).click()
  await page.getByRole('checkbox', { name: roleName, exact: true }).check()
  await page.getByRole('button', { name: '保存成员角色' }).click()
  await expect(member).toContainText(roleName)
  await page.screenshot({ path: '../docs/demo/member-administration.png', fullPage: true })

  await page.getByRole('link', { name: '知识空间' }).click()
  await page.getByRole('button', { name: '新建知识库', exact: true }).click()
  await page.getByLabel('知识库名称').fill(name)
  await page.getByRole('button', { name: '创建知识库', exact: true }).click()
  await expect(page.locator('.modal')).toHaveCount(0)
  await expect(page.locator('.kb-list button.selected')).toContainText(name)
  const filename = `private-${suffix}.md`
  await page.locator('input[type=file]').setInputFiles({ name: filename, mimeType: 'text/markdown', buffer: Buffer.from('退款申请必须在30天内提交。', 'utf8') })
  await expect(page.locator('tr', { hasText: filename })).toContainText('已就绪', { timeout: 30000 })

  const context = await browser.newContext(), colleague = await context.newPage()
  colleague.on('pageerror', error => errors.push(error.message))
  await colleague.goto('/')
  await colleague.getByLabel('邮箱地址').fill(email)
  await colleague.getByLabel('登录密码').fill(password)
  await colleague.getByRole('button', { name: '登录工作空间' }).click()
  await expect(colleague.getByRole('link', { name: '成员与角色' })).toHaveCount(0)
  await colleague.getByRole('link', { name: '知识空间' }).click()
  await expect(colleague.locator('.kb-list')).not.toContainText(name)

  await page.getByRole('button', { name: '知识库权限', exact: true }).click()
  await page.getByLabel('授权主体', { exact: true }).selectOption({ label: roleName })
  await page.getByRole('button', { name: '添加授权' }).click()
  await page.getByRole('button', { name: '保存资料权限' }).click()
  await colleague.reload()
  await colleague.locator('.kb-list button', { hasText: name }).click()
  await expect(colleague.locator('tr', { hasText: filename })).toBeVisible()

  await page.getByRole('button', { name: `管理权限 ${filename}` }).click()
  await page.getByLabel('资料可见范围').selectOption('restricted')
  await page.getByRole('button', { name: '保存资料权限' }).click()
  await colleague.reload()
  await colleague.locator('.kb-list button', { hasText: name }).click()
  await expect(colleague.locator('tr', { hasText: filename })).toHaveCount(0)
  await page.getByRole('button', { name: `管理权限 ${filename}` }).click()
  await page.getByLabel('授权主体', { exact: true }).selectOption({ label: name })
  await page.getByRole('button', { name: '添加授权' }).click()
  await page.screenshot({ path: '../docs/demo/access-management.png', fullPage: true })
  await page.getByRole('button', { name: '保存资料权限' }).click()
  await colleague.reload()
  await colleague.locator('.kb-list button', { hasText: name }).click()
  await expect(colleague.locator('tr', { hasText: filename })).toBeVisible()
  await page.getByRole('button', { name: '知识库权限', exact: true }).click()
  await page.getByRole('button', { name: `移除授权 ${roleName}` }).click()
  await page.getByRole('button', { name: '保存资料权限' }).click()
  await colleague.reload()
  await expect(colleague.locator('.kb-list')).not.toContainText(name)

  await page.getByRole('link', { name: '成员与角色' }).click()
  await page.getByRole('button', { name: `停用 ${email}`, exact: true }).click()
  await expect(page.locator('tr', { hasText: email })).toContainText('已停用')
  await colleague.reload()
  await expect(colleague.getByRole('button', { name: '登录工作空间' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
  await context.close()
})
