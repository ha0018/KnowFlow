import { test, expect } from '@playwright/test'

test('controlled agent search, summary, statistics and source snapshots', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('邮箱地址').fill('admin@acme.demo')
  await page.getByLabel('登录密码').fill(process.env.KNOWFLOW_DEMO_PASSWORD || 'KnowFlowDemo!2026')
  await page.getByRole('button', { name: '登录工作空间' }).click()
  await page.getByRole('link', { name: '只读工具' }).click()
  await page.getByLabel('Agent 资料范围').selectOption({ label: '企业知识中心' })
  await page.getByRole('button', { name: '检索退款规定' }).click()
  await page.getByRole('button', { name: '开始任务' }).click()
  await expect(page.locator('.agent-answer')).toContainText('退款', { timeout: 30000 })
  await expect(page.locator('.agent-step')).toContainText('已完成')
  await page.locator('.agent-answer .references button').first().click()
  await expect(page.locator('.source-excerpt')).toContainText('退款')
  await page.getByRole('button', { name: '关闭引用' }).click()
  await page.getByLabel('Agent 摘要文档').selectOption({ label: '退款政策' })
  await page.getByRole('button', { name: '开始任务' }).click()
  await expect(page.locator('.agent-step')).toContainText('文档摘要')
  await expect(page.locator('.agent-answer')).toContainText('退款', { timeout: 30000 })
  await page.getByRole('button', { name: '统计演示问题' }).click()
  await page.getByRole('button', { name: '开始任务' }).click()
  await expect(page.locator('.agent-answer')).toContainText('36', { timeout: 30000 })
  await expect(page.locator('.agent-step')).toContainText('业务统计')
  await page.locator('.agent-answer .references button').first().click()
  await expect(page.locator('.source-excerpt')).toContainText('"total": 36')
  await expect(page.locator('.source-drawer')).toContainText('演示业务统计')
  await page.getByRole('button', { name: '关闭引用' }).click()
  await page.locator('.controlled-agent').scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../docs/demo/controlled-agent.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
