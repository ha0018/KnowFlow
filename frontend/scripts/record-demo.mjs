import { chromium, expect } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../..', import.meta.url))
const baseURL = process.env.KNOWFLOW_E2E_BASE_URL || 'http://127.0.0.1:5173'
const temporary = path.join(root, '.runtime', 'demo-recording')
const output = path.join(root, 'docs', 'demo', 'product-walkthrough.webm')
await fs.mkdir(temporary, { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ baseURL, viewport: { width: 1280, height: 900 }, recordVideo: { dir: temporary, size: { width: 1280, height: 900 } } })
const page = await context.newPage(), started = Date.now(), steps = [], errors = []
page.on('pageerror', error => errors.push(error.message))
async function hold(name, seconds) {
  steps.push({ name, elapsed_seconds: Math.round((Date.now() - started) / 1000), seconds })
  process.stdout.write(JSON.stringify({ step: name }) + '\n')
  await page.waitForTimeout(seconds * 1000)
}
try {
  await page.goto('/')
  await page.getByLabel('邮箱地址').fill('admin@acme.demo')
  await page.getByLabel('登录密码').fill(process.env.KNOWFLOW_DEMO_PASSWORD || 'KnowFlowDemo!2026')
  await page.getByRole('button', { name: '登录工作空间' }).click()
  await expect(page.getByRole('heading', { name: '知识，从这里连接' })).toBeVisible()
  await hold('工作台与演示范围', 12)
  await page.getByRole('link', { name: '知识空间' }).click()
  await page.locator('.kb-list button', { hasText: '企业知识中心' }).click()
  await expect(page.locator('tr', { hasText: '退款政策' })).toBeVisible()
  await hold('发布版本和知识空间', 10)
  await page.getByRole('link', { name: '知识问答' }).click()
  await page.getByLabel('输入问题').fill('退款超过30天还能申请吗？')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.message.assistant')).toContainText('退款', { timeout: 30000 })
  await hold('有来源的问答', 14)
  await page.locator('.message.assistant .references button').filter({ hasText: '退款政策' }).first().click()
  await expect(page.locator('.source-excerpt')).toContainText('30')
  await hold('原文与引用版本', 12)
  await page.getByRole('button', { name: '关闭引用' }).click()
  await page.getByRole('link', { name: '只读工具' }).click()
  await page.getByLabel('Agent 资料范围').selectOption({ label: '企业知识中心' })
  await hold('受控 Agent 的预算与模式', 8)
  await page.getByRole('button', { name: '统计演示问题' }).click()
  await page.getByRole('button', { name: '开始任务' }).click()
  await expect(page.locator('.agent-answer')).toContainText('36', { timeout: 30000 })
  await hold('实际统计和工具轨迹', 12)
  await page.locator('.agent-answer .references button').first().click()
  await expect(page.locator('.source-excerpt')).toContainText('"total": 36')
  await hold('统计快照和口径', 8)
  await page.getByRole('button', { name: '关闭引用' }).click()
  await page.getByRole('link', { name: '成员与角色' }).click()
  await expect(page.locator('.member-administration')).toBeVisible()
  await hold('成员与角色管理', 12)
  await page.getByRole('link', { name: '知识空间' }).click()
  await page.locator('.kb-list button', { hasText: '企业知识中心' }).click()
  await page.getByRole('button', { name: '知识库权限', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '资料权限管理' })).toBeVisible()
  await hold('知识库权限管理', 12)
  await page.getByRole('button', { name: '关闭权限管理' }).click()
  await page.getByRole('link', { name: '效果评估' }).click()
  await expect(page.getByRole('heading', { name: '效果评估', exact: true })).toBeVisible()
  await hold('冻结评测与待复核状态', 12)
  await page.getByRole('link', { name: '调用记录' }).click()
  await expect(page.getByRole('heading', { name: '调用记录', exact: true })).toBeVisible()
  await hold('用量与模型元数据', 10)
  await page.getByRole('link', { name: '工作台', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await hold('手机布局', 8)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: path.join(root, 'docs', 'demo', 's5-mobile.png'), fullPage: true })
  expect(errors).toEqual([])
  await context.close()
  await page.video().saveAs(output)
  await fs.writeFile(path.join(root, '.runtime', 'demo-recording.json'), JSON.stringify({ source: 'actual_local_browser_recording', base_url: baseURL, started_at: new Date(started).toISOString(), duration_seconds: (Date.now() - started) / 1000, video: 'docs/demo/product-walkthrough.webm', steps, page_errors: errors }, null, 2))
  process.stdout.write('Saved docs/demo/product-walkthrough.webm\n')
} finally {
  await browser.close()
}
